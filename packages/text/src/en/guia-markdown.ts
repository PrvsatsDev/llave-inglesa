import { scoreBand } from '@llave-inglesa/engine';
import type { guiaMarkdown as es } from '../es/guia-markdown.ts';
import { CIFRAS } from '../guia-cifras.ts';
import type { Bloque, Trozo } from '../tipos.ts';
import { EJEMPLOS } from './ejemplos.ts';
import { GUIA } from './guia.ts';
import { SCORE_BAND_TEXT } from './textos.ts';

const URL_APP = 'https://llave-inglesa.vualt.net';

/**
 * The guide in Markdown (docs/GUIDE.md), to read on GitHub. The app’s buttons become directions; `nombres` gives the
 * visible name of each example (in Spanish, as in the fixtures: it is translated here).
 */
export const guiaMarkdown: typeof es = (nombres) => {
  const texto = (trozos: readonly Trozo[]) =>
    trozos
      .map((t) => {
        if (typeof t === 'string') return t;
        if ('negrita' in t) return `**${t.negrita}**`;
        if ('enlace' in t) return `[${t.texto}](${t.enlace})`;
        if ('capitulo' in t) return `[${t.texto}](#${t.capitulo})`;
        const valor = CIFRAS[t.cifra.ejemplo]![t.cifra.metrica];
        return `**${valor}** (${SCORE_BAND_TEXT[scoreBand(valor)].toLowerCase()})`;
      })
      .join('');
  const ejemplo = (id: string) => {
    const nombre = nombres[id] ?? id;
    return `“${EJEMPLOS[nombre] ?? nombre}”`;
  };
  const bloque = (b: Bloque): string => {
    switch (b.tipo) {
      case 'parrafo':
        return texto(b.texto);
      case 'lista':
        return b.items.map((item) => `- ${texto(item)}`).join('\n');
      case 'nota':
        return `> 💡 ${texto(b.texto)}`;
      case 'ejemplo':
        return `> ▶ In the app: open the example ${ejemplo(b.ejemplo)}.`;
      case 'simular':
        return `> ▶ In the app, with the example ${ejemplo(b.ejemplo)}: *${b.texto}*.`;
    }
  };
  const indice = GUIA.map((c, i) => `${i + 1}. [${c.titulo}](#${c.id}): ${c.resumen}`).join('\n');
  const capitulos = GUIA.map((c, i) => [`<a id="${c.id}"></a>`, `## ${i + 1}. ${c.titulo}`, ...c.bloques.map(bloque)].join('\n\n'));
  return `# User guide

<!-- Generated by scripts/guia.ts from packages/text/src/en/guia.ts: do not edit by hand. -->

This guide is also inside the app (${URL_APP}, menu *File → User guide*), where it is
interactive: its buttons open the examples and simulate on the map. The figures are the ones the engine
calculates in this version. [Versión en español](GUIA.md).

${indice}

${capitulos.join('\n\n')}
`;
};
